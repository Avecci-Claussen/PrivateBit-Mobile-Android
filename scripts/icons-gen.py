import json, sys, math
M=json.load(open('/workspace/wallet/v2/work/PrivateBit/src/ui/mark-paths.json'))
BG="#151027"
def geom(shift, s):
    # mark grid 64; bbox centered at 32,32; optical shift to the right in grid units
    tx=54-32*s+shift*s; ty=54-32*s
    return tx,ty
def mark_svg(shift,s,mono=False):
    tx,ty=geom(shift,s)
    if mono:
        inner=f'<path fill="#fff" d="{M["STEM"]} {M["UP"]} {M["LO"]}"/>'
    else:
        inner=f'<path fill="#F4F1EA" d="{M["STEM"]}"/><path fill="#8F74FF" d="{M["UP"]}"/><path fill="#FF8A1F" d="{M["LO"]}"/>'
    return f'<g transform="translate({tx:.2f} {ty:.2f}) scale({s})">{inner}</g>'
def mask_path(kind):
    # visible 72x72 region centered at 54,54 (18..90)
    if kind=="circle": return '<circle cx="54" cy="54" r="36"/>'
    if kind=="rounded": return '<rect x="18" y="18" width="72" height="72" rx="13"/>'
    if kind=="teardrop": return '<path d="M54 18A36 36 0 0 0 18 54A36 36 0 0 0 54 90H90V54A36 36 0 0 0 54 18Z"/>'
    if kind=="squircle":
        pts=[]
        for i in range(200):
            t=2*math.pi*i/200; c,sn=math.cos(t),math.sin(t)
            x=54+36*math.copysign(abs(c)**(2/5),c); y=54+36*math.copysign(abs(sn)**(2/5),sn)
            pts.append(f'{x:.2f},{y:.2f}')
        return f'<polygon points="{" ".join(pts)}"/>'
def icon_svg(shift,s,kind,px,guides=False):
    g=''
    if guides:
        g='<circle cx="54" cy="54" r="33" fill="none" stroke="#3fd" stroke-width=".3" stroke-dasharray="1 1"/><line x1="54" y1="18" x2="54" y2="90" stroke="#3fd" stroke-width=".2"/>'
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{px}" height="{px}" viewBox="18 18 72 72"><defs><clipPath id="m">{mask_path(kind)}</clipPath></defs><g clip-path="url(#m)"><rect x="0" y="0" width="108" height="108" fill="{BG}"/>{mark_svg(shift,s)}{g}</g></svg>'
